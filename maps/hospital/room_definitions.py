# ─────────────────────────────────────────────────────────────────────────────
# Lookup Dictionaries  (built at import time — O(1) room resolution)
# ─────────────────────────────────────────────────────────────────────────────

# room_id → RoomDefinition
ROOMS_BY_ID: Dict[str, RoomDefinition] = {
    room.room_id: room for room in ROOM_DATABASE
}

# nav_node_id → RoomDefinition
ROOMS_BY_NODE: Dict[str, RoomDefinition] = {
    room.nav_node_id: room for room in ROOM_DATABASE
}

# Alias map: normalised lowercase string → room_id
_ALIAS_MAP: Dict[str, str] = {}
for _room in ROOM_DATABASE:
    _ALIAS_MAP[_room.label.lower()] = _room.room_id
    for _alias in _room.aliases:
        _ALIAS_MAP[_alias.lower()] = _room.room_id

# Category → list of rooms
ROOMS_BY_CATEGORY: Dict[RoomCategory, List[RoomDefinition]] = {}
for _room in ROOM_DATABASE:
    ROOMS_BY_CATEGORY.setdefault(_room.category, []).append(_room)


# ─────────────────────────────────────────────────────────────────────────────
# Public Query Functions
# ─────────────────────────────────────────────────────────────────────────────

def lookup_room_by_alias(query: str) -> Optional[RoomDefinition]:
    """Find a room by any of its names or aliases (case-insensitive).

    Args:
        query: User-provided room name string (e.g. "pharmacy", "Room 205").

    Returns:
        RoomDefinition if found, else None.
    """
    room_id = _ALIAS_MAP.get(query.lower().strip())
    if room_id:
        return ROOMS_BY_ID.get(room_id)
    # Partial match fallback (startswith)
    q = query.lower().strip()
    for alias, rid in _ALIAS_MAP.items():
        if alias.startswith(q) or q.startswith(alias):
            return ROOMS_BY_ID.get(rid)
    return None


def get_room_center(room_id: str) -> Optional[Tuple[int, int]]:
    """Return (row, col) geometric centre of room, or None if not found."""
    room = ROOMS_BY_ID.get(room_id)
    return (room.center_row, room.center_col) if room else None


def get_room_entry(room_id: str) -> Optional[Tuple[int, int]]:
    """Return (row, col) entry point of room, or None if not found."""
    room = ROOMS_BY_ID.get(room_id)
    return room.entry_point if room else None

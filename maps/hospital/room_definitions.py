# ─────────────────────────────────────────────────────────────────────────────
# Room Priority
# ─────────────────────────────────────────────────────────────────────────────

class RoomPriority(Enum):
    """Navigation priority — lower value = faster response."""
    CRITICAL   = 0   # Emergency, ICU, OT
    HIGH       = 1   # NICU, Trauma, Isolation
    MEDIUM     = 2   # Lab, Pharmacy, Imaging
    NORMAL     = 3   # Patient wards, OPD
    LOW        = 4   # Admin, Amenities
    UTILITY    = 5   # Charging, Storage


# ─────────────────────────────────────────────────────────────────────────────
# Room Dataclass
# ─────────────────────────────────────────────────────────────────────────────

@dataclass
class RoomDefinition:
    """Complete definition of a hospital room or area.

    Coordinate convention (matches numpy row/col):
        row increases downward (south), col increases rightward (east).
        (0,0) is the top-left corner of the grid.

    The bounding box is inclusive on all four sides; the room interior
    is carved with a 1-cell wall inset by hospital_map.py.

    Attributes:
        room_id:      Unique alphanumeric identifier, e.g. "ICU-01".
        label:        Short display name shown on the map HUD.
        category:     Semantic category (RoomCategory enum).
        top_row:      Grid row of the top-left corner.
        left_col:     Grid column of the top-left corner.
        bottom_row:   Grid row of the bottom-right corner (inclusive).
        right_col:    Grid column of the bottom-right corner (inclusive).
        entry_row:    Row of the room's doorway / entry point.
        entry_col:    Column of the room's doorway / entry point.
                      Must be adjacent (1 cell) to a carved corridor.
        priority:     Navigation priority for emergency routing.
        aliases:      Alternative names used by the NLU command resolver.
        color_key:    Key into ColorConfig for rendering.
        nav_node_id:  Unique node ID in the navigation graph (= room_id).
        description:  Brief description shown in the UI tooltip.
    """

    room_id:     str
    label:       str
    category:    RoomCategory
    top_row:     int
    left_col:    int
    bottom_row:  int
    right_col:   int
    entry_row:   int
    entry_col:   int
    priority:    RoomPriority       = RoomPriority.NORMAL
    aliases:     List[str]          = field(default_factory=list)
    color_key:   str                = "ROOM_GENERIC"
    nav_node_id: str                = ""
    description: str                = ""

    def __post_init__(self) -> None:
        if not self.nav_node_id:
            self.nav_node_id = self.room_id

    # ── Derived geometry ──────────────────────────────────────────────────────

    @property
    def center_row(self) -> int:
        return (self.top_row + self.bottom_row) // 2

    @property
    def center_col(self) -> int:
        return (self.left_col + self.right_col) // 2

    @property
    def center(self) -> Tuple[int, int]:
        """Return (center_row, center_col) tuple."""
        return (self.center_row, self.center_col)

    @property
    def name(self) -> str:
        """Alias for label."""
        return self.label

    @property
    def width(self) -> int:
        return self.right_col - self.left_col + 1

    @property
    def height(self) -> int:
        return self.bottom_row - self.top_row + 1

    @property
    def bounds(self) -> Tuple[int, int, int, int]:
        return (self.top_row, self.left_col, self.bottom_row, self.right_col)

    @property
    def entry_point(self) -> Tuple[int, int]:
        return (self.entry_row, self.entry_col)

    def contains(self, row: int, col: int) -> bool:
        return (self.top_row <= row <= self.bottom_row
                and self.left_col <= col <= self.right_col)

    def __repr__(self) -> str:
        return (f"Room({self.room_id!r}, label={self.label!r}, "
                f"entry=({self.entry_row},{self.entry_col}))")


